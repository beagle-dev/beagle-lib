"""Paths shared by the TinyGPU offline harness (see README.md). Importing this touches no device.

Override with environment variables:
  TINYGRAD_PATH        the pinned tinygrad tree (default ~/Dropbox/Projects/tinygrad-hcq1, as nv_dispatch_daemon.py)
  BEAGLE_TINYGPU_DATA  cached cubins, firmware, captures, references, run logs (default ~/.beagle/tinygpu)
  TINYGPU_TEST_WORK    scratch outputs of a test run (default ~/Library/Caches/beagle-tinygpu-tests: per computer, since the
                       repo may be a synced folder shared between computers)
  TINYGPU_TEST_CACHE   build outputs that depend only on the repository, shared by runs with different work directories
                       (default TINYGPU_TEST_WORK): the PTX modules and their extractors, and build_cpp's builds of
                       repository sources into the work directory. It may contain the work directories; those builds
                       then go to its <path relative to the work directory> (a2_boot, a2b, c2, c4, golden_cubins, golden_*,
                       tinygpu_amd_compile), so a work directory inside it must not be named like one of those
"""
import os, re, sys, fcntl, shutil, hashlib, pathlib, tempfile, threading, subprocess

HERE = pathlib.Path(__file__).resolve().parent
GPU_DIR = HERE.parent                                   # libhmsbeagle/GPU
ORACLE = HERE / "oracle"                                # the NV and AMD daemons and their helpers, tinygrad plus BEAGLE's patches (C13b, A2l)
REPO = GPU_DIR.parent.parent
TINYGRAD_PATH = os.environ.get("TINYGRAD_PATH", str(pathlib.Path.home() / "Dropbox/Projects/tinygrad-hcq1"))
DATA = pathlib.Path(os.environ.get("BEAGLE_TINYGPU_DATA", pathlib.Path.home() / ".beagle/tinygpu"))
WORK = pathlib.Path(os.environ.get("TINYGPU_TEST_WORK", pathlib.Path.home() / "Library/Caches/beagle-tinygpu-tests"))
CACHE = pathlib.Path(os.environ.get("TINYGPU_TEST_CACHE", WORK))
KERNELS_H = GPU_DIR / "kernels/BeagleTinyGPU_kernels.h"   # generated by the TinyGPUKernels build target
VARIANTS = tuple(f"SP_{n}" for n in (4, 16, 32, 48, 64, 80, 128, 192, 256))   # make_tinygpu_kernels.sh's SP modules

def setup():
    """Put the pinned tinygrad, the oracle (the NV and AMD daemons and their helpers) and libhmsbeagle/GPU (the table
    generators) first on sys.path, and make any real device access fail: harness code must only ever reach fakes."""
    for p in (str(GPU_DIR), str(ORACLE), TINYGRAD_PATH):
        if p not in sys.path: sys.path.insert(0, p)
    WORK.mkdir(parents=True, exist_ok=True)
    block_real_devices()
    block_network()

def block_network():
    """Harness code never downloads. tinygrad's fetch and fetch_fw download whatever their cache lacks: on 2026-10-01 a probe
    that went through fw.hashes fetched three AMD blobs the boot never uses. So every download raises (fetch() imports
    urllib.request at call time)."""
    import urllib.request
    def offline(*a, **k): raise RuntimeError("tinygpu_tests: network access attempted (the offline harness never downloads)")
    urllib.request.urlopen = offline

def block_real_devices():
    """tinygrad opens the real eGPU through APLRemotePCIDevice (which also starts TinyGPU.app) whenever something
    instantiates a device, e.g. its atexit hook finalizing Device._opened_devices. On 2026-09-24 a test left "NV"
    in that set and the hook booted the real RTX 4060 at exit (STATUS.md R16). Every constructor that could reach
    the real hardware now raises. Fakes that subclass APLRemotePCIDevice with their own __init__ (nv_dispatch_daemon's
    inherited-fd device, which the tests give a socketpair) are unaffected."""
    from tinygrad.runtime.support import system
    def refuse(*a, **k): raise RuntimeError("tinygpu_tests: real device access is blocked in the offline harness")
    system.APLRemotePCIDevice.__init__ = refuse
    system.APLRemotePCIDevice.ensure_app = classmethod(refuse)
    system.RemotePCIDevice.__init__ = refuse
    system.PCIDevice.__init__ = refuse
    import atexit
    from tinygrad import device
    atexit.register(lambda: device.Device._opened_devices.clear())   # runs before tinygrad's own hook (LIFO)

def cxx():
    return os.environ.get("CXX", "clang++")

def build_cpp(src, out, *extra):
    """Compile a harness C++ program against the in-tree headers. Skipped when <out> was built from the same inputs: the
    compiler (its --version), the command line, the preprocessed source (every header's content, wherever the include path
    found it: perturbation tests shadow headers with -iquote) and the files an .incbin names, a key kept next to the build
    with the binary's sha256. A compile goes to a private directory, then replaces the build (os.replace: a process running
    the old binary keeps it), under a lock, so concurrent callers compile once. A build of repository sources only, into
    the work directory, is made at the same relative path in TINYGPU_TEST_CACHE and copied to <out>."""
    out = pathlib.Path(out)
    cmd = [cxx(), "-std=c++17", "-O1", "-Wall", "-Wextra", f"-I{REPO}", *extra]
    key = _build_key(cmd, src, out.name)
    inputs = [src] + [a for a in extra if not str(a).startswith("-")]
    shared = (WORK.resolve() != CACHE.resolve() and _inside(out, WORK) and (_inside(WORK, CACHE) or not _inside(out, CACHE))
              and all(_inside(i, REPO) for i in inputs))   # (out inside a cache that is inside WORK: already a cache path)
    built = CACHE / out.resolve().relative_to(WORK.resolve()) if shared else out
    built.parent.mkdir(parents=True, exist_ok=True)
    stamp = built.with_name(f".{built.name}.key")
    with open(built.with_name(f".{built.name}.lock"), "a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if key is None or not _stamped(built, stamp, key):
            tmp = tempfile.mkdtemp(dir=built.parent, prefix=f".{built.name}.")
            try:
                subprocess.run(cmd + ["-o", os.path.join(tmp, built.name), str(src)], check=True)
                stamp.unlink(missing_ok=True)
                os.replace(os.path.join(tmp, built.name), built)
                if key: _write_atomic(stamp, f"{key} {_sha256_file(built)}\n".encode())
            finally: shutil.rmtree(tmp, ignore_errors=True)
        if built.resolve() != out.resolve() and not (out.is_file() and _sha256_file(out) == _sha256_file(built)):
            out.parent.mkdir(parents=True, exist_ok=True)   # a fresh work directory may not have it yet
            part = out.with_name(f".{out.name}.part.{os.getpid()}.{threading.get_ident()}")
            shutil.copy2(built, part)
            os.replace(part, out)

_compiler = {}
def _build_key(cmd, src, name):
    """build_cpp's key, or None when the preprocessor fails (the compile then runs, and reports the error)."""
    if cmd[0] not in _compiler:
        exe = shutil.which(cmd[0]) or cmd[0]
        _compiler[cmd[0]] = f"{exe}\n" + subprocess.run([exe, "--version"], capture_output=True, text=True, check=True).stdout
    pre = subprocess.run(cmd + ["-E", str(src)], capture_output=True)
    if pre.returncode != 0: return None
    h = hashlib.sha256()
    for part in (_compiler[cmd[0]], "\0".join(map(str, cmd + ["-o", name, src])),
                 *(f"{v}={os.environ.get(v, '')}" for v in ("SDKROOT", "MACOSX_DEPLOYMENT_TARGET", "LIBRARY_PATH"))):
        h.update(part.encode() + b"\0")
    h.update(pre.stdout)
    for path in re.findall(rb'\.incbin\s+"([^"]+)"', pre.stdout):   # the assembler's inputs, which the preprocessor does not read
        h.update(path + b"\0" + (hashlib.sha256(pathlib.Path(os.fsdecode(path)).read_bytes()).digest() if os.path.isfile(path) else b"-"))
    return h.hexdigest()

def _stamped(built, stamp, key):
    try: k, digest = stamp.read_text().split()
    except (OSError, ValueError): return False
    return k == key and built.is_file() and _sha256_file(built) == digest

def _sha256_file(p): return hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest()

def _inside(p, root):
    return pathlib.Path(p).resolve().is_relative_to(pathlib.Path(root).resolve())

def _write_atomic(path, data):
    """path's new contents, written under a temporary name and renamed into place: a concurrent reader sees the old or the new."""
    part = path.with_name(f"{path.name}.part.{os.getpid()}.{threading.get_ident()}")
    part.write_bytes(data)
    os.replace(part, path)

def ptx(variant):
    """BEAGLE's PTX module for a kernel variant, exactly as the plugin embeds it (KERNELS_STRING_<variant>)."""
    CACHE.mkdir(parents=True, exist_ok=True)
    out = CACHE / f"beagle_{variant}.ptx"
    if not out.exists() or out.stat().st_mtime < KERNELS_H.stat().st_mtime:
        exe = CACHE / f"ptx_extract_{variant}"
        build_cpp(HERE / "ptx_extract.cpp", exe, f"-DVARIANT=KERNELS_STRING_{variant}", "-w")
        _write_atomic(out, subprocess.run([str(exe)], check=True, capture_output=True).stdout)
    return out.read_bytes()

def cubin_path(ptx_bytes, arch):
    """Cache key: the PTX's sha256 prefix, so a regenerated kernels header never reuses a stale cubin."""
    return DATA / "cubins" / f"{hashlib.sha256(ptx_bytes).hexdigest()[:16]}_{arch}.cubin"

def cubin(variant, arch):
    """The ptxas cubin for a variant, compiled once with nv_compile_helper.compile_ptx (the daemon's own compile)."""
    p = cubin_path(ptx(variant), arch)
    if not p.exists():
        setup()
        import nv_compile_helper as nch
        print(f"compiling {variant} for {arch} with ptxas (not cached at {p}) ...", flush=True)
        p.parent.mkdir(parents=True, exist_ok=True)
        _write_atomic(p, nch.compile_ptx(str(CACHE / f"beagle_{variant}.ptx"), arch, kernel_name="_all"))
    return p.read_bytes()
